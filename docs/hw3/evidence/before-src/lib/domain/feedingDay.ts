/**
 * Calendar feeding day (YYYY-MM-DD) of an instant in an IANA timezone.
 * Callers pass `now` or a session `endTime`; this never reads the clock.
 */
export function feedingDayOf(now: Date, timeZone: string): string {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(now);

  const year = parts.find((part) => part.type === "year")?.value;
  const month = parts.find((part) => part.type === "month")?.value;
  const day = parts.find((part) => part.type === "day")?.value;

  return `${year}-${month}-${day}`;
}
